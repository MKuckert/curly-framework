<?php
	class ClassBuilder {
		private $outdir = '';
		private $classDef = null;
		private $buffer = '';
		public function getClassDef() {
			return( $this->classDef );
		}
		public function setClassDef( array $def ) {
			$this->classDef = $def;
		}
		
		public function build( $dir ) {
			$this->outdir = $dir;
			foreach( $this->classDef as $class ) {
				$this->buffer = '';
				$this->buildClass( $class );
			}
		}
		
		protected function buildClass( array $class ) {
			$this->line( '<?php' );
			$this->line( '', 1 );
			
			$this->comment(
				$class['name']."\n"
				."This file was automatically generated by the xmi2php-converter.\n"
				."(c) 2008 Martin Kuckert\n\n"
				."@author <AUTHOR>"
			, 1 );
			$this->line( ( $class['abstract'] ? 'abstract ' : '' )
						. 'class '.$class['name'].' {', 1 );
			$this->line( '', 2 );
			$this->buildAttributes( $class['attributes'] );
			$this->buildMethods( $class['methods'] );
			
			$this->line( '}', 1 );
			$this->line( '', 1 );
			$this->buffer .= "?>";
			
			file_put_contents( $this->outdir.'/'.$class['name'].'.php', $this->buffer );
		}
		
		protected function buildMethods( array $methods ) {
			foreach( $methods as $method ) {
				$this->line( ( $method['abstract'] ? 'abstract ' : '' )
							. $method['visibility'].' function '.$method['name'].'('
							. $this->buildParameter( $method['parameter'] ).') {', 2 );
				$this->line( '', 3 );
				$this->line( '}', 2 );
				$this->line( '', 2 );
			}
		}
		
		protected function buildParameter( array $parameter ) {
			if( count( $parameter )<=0 ) {
				return( '' );
			}
			
			$params = array();
			foreach( $parameter as $param ) {
				$params[] = '$'.$param['name'];
			}
			return( ' '.implode( ', ', $params ).' ' );
		}
		
		protected function buildAttributes( array $attributes ) {
			foreach( $attributes as $attribute ) {
				$this->line( $attribute['visibility'].' $'.$attribute['name'].';', 2 );
				$this->line( '', 2 );
			}
		}
		
		protected function line( $str, $depth=0 ) {
			$this->buffer .= str_repeat( "\t", $depth ).$str."\n";
		}
		
		protected function comment( $str, $depth=0 ) {
			$this->line( '/**', $depth );
			
			$str = wordwrap( $str, 77-($depth*4), "\n", true );
			$str = explode( "\n", $str );
			foreach( $str as $line ) {
				$this->line( ' * '.$line, $depth );
			}
			$this->line( ' */', $depth );
		}
	}
?>